// Creates <repo>/.env with freshly generated secrets. Zero dependencies, works on Windows/macOS/Linux.
// Usage: npm run setup           (refuses to overwrite an existing .env)
import fs from 'node:fs';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const target = `${root}.env`;

if (fs.existsSync(target)) {
  console.error(`.env already exists at ${target}. Delete it first if you want fresh secrets.`);
  process.exit(1);
}

const hex = () => crypto.randomBytes(32).toString('hex');
const apiKeyPepper = hex();
const adminApiKey = hex();
const cacheEncryptionKey = crypto.randomBytes(32).toString('base64');

const text = `# Generated by npm run setup. NEVER commit .env.
FREE_ONLY=true

# Databases (MongoDB Atlas + Upstash Redis, or local)
MONGO_URI=mongodb://localhost:27017/llmgw
REDIS_URL=redis://localhost:6379

# Secrets
API_KEY_PEPPER=${apiKeyPepper}
ADMIN_API_KEY=${adminApiKey}
CACHE_ENCRYPTION_KEY=${cacheEncryptionKey}

# Free LLM provider: get a key at https://console.groq.com/keys
GROQ_API_KEY=
GROQ_MODEL_CHEAP=openai/gpt-oss-20b
GROQ_MODEL_MID=qwen/qwen3.8-27b
GROQ_MODEL_PREMIUM=openai/gpt-oss-120b

# Optional local Ollama
ENABLE_OLLAMA=false
OLLAMA_BASE_URL=http://localhost:11434

# Embeddings & Cache
EMBEDDINGS=local
CACHE_ENABLED=true
CACHE_THRESHOLD=0.95

# Timing & Behaviour
HEDGE_AFTER_MS=4000
IDLE_TIMEOUT_MS=30000
BLOCK_INJECTION=false
CORS_ORIGINS=http://localhost:5173
TRUST_PROXY=0
MCP_ALLOW_WRITES=false
`;

fs.writeFileSync(target, text, { mode: 0o600 });
console.log(`Created ${target}`);
console.log(`Admin console key (save it, it is the dashboard login):\n  ${adminApiKey}`);
